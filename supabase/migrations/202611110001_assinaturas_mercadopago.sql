-- Automação de assinatura mensal do OrçaZap via Mercado Pago.
-- Execute no SQL Editor do projeto Supabase antes de publicar a aplicação.

create table if not exists public.assinaturas (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  mp_preapproval_id text not null unique,
  external_reference text not null unique,
  plano_codigo text not null references public.planos(codigo),
  status text not null default 'pending',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists assinaturas_user_id_idx on public.assinaturas(user_id);
alter table public.assinaturas enable row level security;
revoke all on public.assinaturas from anon, authenticated;
grant all on public.assinaturas to service_role;

create table if not exists public.pagamentos_assinatura (
  mp_pagamento_id text primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  processado_em timestamptz not null default now()
);

alter table public.pagamentos_assinatura enable row level security;
revoke all on public.pagamentos_assinatura from anon, authenticated;
grant all on public.pagamentos_assinatura to service_role;

-- Ativação idempotente: uma notificação repetida do Mercado Pago não estende
-- a licença duas vezes. Só o backend usando a service role pode invocar.
create or replace function public.processar_pagamento_assinatura(
  p_pagamento_id text,
  p_user_id uuid,
  p_plano_codigo text,
  p_aprovado_em timestamptz
)
returns boolean
language plpgsql
security definer
set search_path to ''
as $function$
declare
  v_inserido integer;
begin
  if coalesce(auth.role(), '') <> 'service_role' then
    raise exception 'Acesso negado';
  end if;

  if not exists (
    select 1 from public.planos p
    where p.codigo = p_plano_codigo and p.ativo = true
  ) then
    raise exception 'Plano inválido ou inativo';
  end if;

  insert into public.pagamentos_assinatura (mp_pagamento_id, user_id)
  values (p_pagamento_id, p_user_id)
  on conflict (mp_pagamento_id) do nothing;
  get diagnostics v_inserido = row_count;

  if v_inserido = 0 then
    return false;
  end if;

  insert into public.licencas (user_id, plano_codigo, status, inicio_em, expira_em)
  values (
    p_user_id,
    p_plano_codigo,
    'ativa',
    coalesce(p_aprovado_em, now()),
    coalesce(p_aprovado_em, now()) + interval '1 month'
  )
  on conflict (user_id) do update
  set plano_codigo = excluded.plano_codigo,
      status = 'ativa',
      expira_em = greatest(
        coalesce(public.licencas.expira_em, excluded.inicio_em),
        excluded.inicio_em
      ) + interval '1 month',
      updated_at = now();

  return true;
end;
$function$;

revoke all on function public.processar_pagamento_assinatura(text, uuid, text, timestamptz) from public, anon, authenticated;
grant execute on function public.processar_pagamento_assinatura(text, uuid, text, timestamptz) to service_role;

